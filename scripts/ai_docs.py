#!/usr/bin/env python3
'Index project docs and map source paths to focused documentation.'
import argparse
import fnmatch
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / 'docs'
INDEX = DOCS / 'INDEX.md'

def parse_doc(path):
    raw = path.read_text(encoding='utf-8-sig')
    meta = {}
    if raw.startswith('---\n'):
        segments = raw.split('---\n', 2)
        if len(segments) >= 3:
            for line in segments[1].splitlines():
                if ':' not in line:
                    continue
                key, val = (part.strip() for part in line.split(':', 1))
                if key == 'code_paths':
                    try:
                        meta[key] = json.loads(val)
                    except json.JSONDecodeError:
                        meta[key] = None
                else:
                    meta[key] = val.strip('"').strip("'")
    return meta, raw

def docs():
    return [(p, *parse_doc(p)) for p in sorted(DOCS.rglob('*')) if p.is_file()
            and p.suffix.lower() in ('.md', '.txt') and p not in (INDEX, DOCS / 'README.md')]

def render(items):
    lines = ['# Documentation index', '', '> Generated by python3 scripts/ai_docs.py index; do not edit manually.', '',
             '[Start](README.md) | [State](ops/PROJECT_STATE.md) | [Handoff](ops/HANDOFF.md)', '',
             '## Focused documentation', '']
    focused, legacy = [], []
    for path, meta, _ in items:
        rel = path.relative_to(DOCS).as_posix()
        if meta.get('title') and isinstance(meta.get('code_paths'), list):
            focused.append('- [' + str(meta['title']) + '](' + rel + ') — ' + str(meta.get('summary','')) +
                           ' (source: ' + ', '.join(meta['code_paths'] or ['general']) + ')')
        else:
            legacy.append('- [' + rel + '](' + rel + ')')
    lines += focused or ['_None_']
    lines += ['', '## Preserved legacy documents', '']
    lines += legacy or ['_None_']
    return '\n'.join(lines) + '\n'

def related(path, items):
    path = path.replace('\\', '/').lstrip('./')
    matches = []
    for doc, meta, _ in items:
        for glob in meta.get('code_paths') or []:
            if isinstance(glob, str) and fnmatch.fnmatchcase(path, glob):
                try:
                    matches.append(doc.relative_to(ROOT).as_posix())
                except ValueError:
                    matches.append(doc.as_posix())
                break
    return matches

def check(items):
    errors = []
    for path, meta, body in items:
        if not meta:
            continue   # older documents are kept untouched
        if not meta.get('title') or not meta.get('summary') or not isinstance(meta.get('code_paths'), list):
            errors.append(path.relative_to(ROOT).as_posix() + ': invalid frontmatter')
        if len(body.splitlines()) > 350:
            errors.append(path.relative_to(ROOT).as_posix() + ': focused document exceeds 350 lines')
    if not INDEX.exists() or INDEX.read_text(encoding='utf-8') != render(items):
        errors.append('docs/INDEX.md stale, run python3 scripts/ai_docs.py index')
    for error in errors:
        print('ERROR:', error, file=sys.stderr)
    return 1 if errors else 0

def main():
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest='command', required=True)
    commands.add_parser('index')
    commands.add_parser('check')
    rel = commands.add_parser('related')
    rel.add_argument('path')
    args = parser.parse_args()
    items = docs()
    if args.command == 'index':
        INDEX.write_text(render(items), encoding='utf-8')
        print('Indexed', len(items), 'documents')
        return 0
    if args.command == 'check':
        result = check(items)
        if not result:
            print('Index and metadata OK')
        return result
    matches = related(args.path, items)
    print('\n'.join(matches) if matches else 'No direct mapping. Consult docs/INDEX.md.')
    return 0

if __name__ == '__main__':
    sys.exit(main())
